    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        // TODO add your handling code here:
        String title = titleField.getText();
        String author = authorField.getText();
        String isbn = isbnField.getText();
        
       if(typeBox.getSelectedItem().equals("Printed")){
           int pages = Integer.parseInt(pagesField.getText());
           library.addBook(new PrintedBook(title, author, isbn, pages));
           }else{
           double size = Double.parseDouble(sizeField.getText());
           library.addBook(new eBook(title,author,isbn,size));
           
       }
       JOptionPane.showMessageDialog(this, "Book added to library.");
       titleField.setText("");
       authorField.setText("");
       isbnField.setText("");
       pagesField.setText("");
       sizeField.setText("");   
    }//GEN-LAST:event_saveBtnActionPerformed

