    private void removeConfirmBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeConfirmBtnActionPerformed
        // TODO add your handling code here:
        int idx = removeList.getSelectedIndex();
        if (idx >= 0) {
        Book selectedBook = library.getBooks()[idx];
        library.removeBook(selectedBook);

        Book[] books = library.getBooks();
        String[] display = new String[books.length];
        for (int i = 0; i < books.length; i++) {
            display[i] = books[i].toString();
        }
        
        removeList.setListData(display);

        JOptionPane.showMessageDialog(this, "Removed: " + selectedBook);
    } else {
        JOptionPane.showMessageDialog(this, "Please select a book first.", "No Selection", JOptionPane.WARNING_MESSAGE);
    }
        
    }//GEN-LAST:event_removeConfirmBtnActionPerformed

